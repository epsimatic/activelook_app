/// Returns [input] with Cyrillic letters replaced by their Latin equivalents.
///
/// Because the built-in glasses fonts are ASCII-only, this is what the panel
/// can actually display. Everything else (digits, punctuation, Latin letters,
/// emoji) is left untouched.
String toGlassesText(String input) {
  final buffer = StringBuffer();
  for (final rune in input.runes) {
    final character = String.fromCharCode(rune);
    buffer.write(_letterMap[character] ?? character);
  }
  return buffer.toString();
}
