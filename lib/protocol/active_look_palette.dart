/// Frequently used palette entries, named after their role on engo3.
abstract final class ActiveLookColor {
  /// Brightest entry — reads as white/amber in the optics.
  static const int bright = 0xFF;

  /// Secondary text: dimmer, less aggressive on the eye.
  static const int secondary = 0xC7;

  /// Green — "good"/on-target.
  static const int green = 0x83;

  /// Orange/amber — caution.
  static const int orange = 0x3C;

  /// Orange-red — alert. The palette has no deep red: this is the most
  /// red-looking entry that is still bright enough to read.
  static const int red = 0x14;
}

/// Returns the preview ARGB color for a palette [value], falling back to black
/// for values that are not part of the palette.
int paletteColor(int value) => activeLookPalette[value] ?? 0xFF000000;
